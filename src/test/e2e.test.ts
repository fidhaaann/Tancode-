import assert from 'node:assert/strict';
import test from 'node:test';
import http from 'node:http';
import type { AddressInfo } from 'node:net';
import { ExplanationCache } from '../model/cache';
import { OllamaClient } from '../model/ollama';
import { DocLike, ExplanationResult, ExplanationService } from '../model/service';
import { renderBody } from '../view';

// End-to-end tests over a real HTTP server and real fetch — proves the wire
// path (POST /api/generate, stream:false, JSON parsing, think-stripping)
// carries a successful Ollama response all the way to the rendered panel.
// No live Ollama required.

function doc(overrides: Partial<DocLike> = {}): DocLike {
	return {
		languageId: 'typescript',
		fileName: '/w/app.ts',
		uri: { fsPath: '/w/app.ts', toString: () => 'file:///w/app.ts' },
		version: 1,
		getText: () => 'export function main() {}',
		...overrides,
	};
}

const RULES_FALLBACK = {
	fileName: 'app.ts', languageId: 'typescript', languageName: 'TypeScript',
	lineCount: 1, nonBlankLineCount: 1,
	summary: 'rules say it exports things', symbols: [], imports: [], exports: [], details: [],
};

interface CapturedRequest {
	path: string;
	body: {
		model?: string; system?: string; prompt?: string; stream?: boolean;
		think?: boolean; keep_alive?: string; options?: { num_predict?: number };
	};
}

async function withServer(
	handler: (req: http.IncomingMessage, res: http.ServerResponse, captured: CapturedRequest) => void,
	run: (baseUrl: string, captured: CapturedRequest[]) => Promise<void>,
): Promise<void> {
	const captured: CapturedRequest[] = [];
	const server = http.createServer((req, res) => {
		let body = '';
		req.on('data', chunk => { body += chunk; });
		req.on('end', () => {
			const entry: CapturedRequest = { path: req.url ?? '', body: {} };
			try { entry.body = JSON.parse(body); } catch { /* leave empty */ }
			captured.push(entry);
			handler(req, res, entry);
		});
	});
	await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
	const port = (server.address() as AddressInfo).port;
	try {
		await run(`http://127.0.0.1:${port}`, captured);
	} finally {
		await new Promise<void>(resolve => server.close(() => resolve()));
	}
}

function makeService(baseUrl: string, timeoutMs = 5000): ExplanationService {
	return new ExplanationService(
		new OllamaClient(baseUrl, timeoutMs), // real undici fetch
		new ExplanationCache<ExplanationResult>(),
		() => RULES_FALLBACK,
		() => true,
		{ model: 'qwen3:8b', maxSourceBytes: 65536, fallbackToRules: true },
		{ info: () => undefined },
	);
}

test('e2e: POST /api/generate carries model, prompt and stream:false', async () => {
	await withServer((_req, res) => {
		res.writeHead(200, { 'Content-Type': 'application/json' });
		res.end(JSON.stringify({ response: 'The file registers commands.' }));
	}, async (baseUrl, captured) => {
		const res = await makeService(baseUrl).explain(doc(), 'summary');
		assert.equal(res.status, 'ok');
		assert.equal(captured.length, 1);
		assert.equal(captured[0].path, '/api/generate');
		assert.equal(captured[0].body.model, 'qwen3:8b');
		assert.equal(captured[0].body.stream, false);
		assert.equal(captured[0].body.think, false, 'thinking disabled for faster replies');
		assert.equal(captured[0].body.keep_alive, '10m', 'model stays warm between requests');
		assert.equal(captured[0].body.options?.num_predict, 600, 'summary uses a complete-answer output budget');
		assert.match(captured[0].body.prompt ?? '', /export function main/);
		assert.equal(typeof captured[0].body.system, 'string');
	});
});

test('e2e: successful response reaches the rendered panel with model badge', async () => {
	await withServer((_req, res) => {
		res.writeHead(200, { 'Content-Type': 'application/json' });
		res.end(JSON.stringify({
			response: '<think>let me look at this file</think>The file registers two commands.',
		}));
	}, async baseUrl => {
		const res = await makeService(baseUrl).explain(doc(), 'summary');
		assert.equal(res.status, 'ok');
		if (res.status !== 'ok' || res.source !== 'model') {
			return assert.fail('expected a model result');
		}
		// Thinking output is stripped, not displayed.
		assert.equal(res.text, 'The file registers two commands.');
		const html = renderBody({
			kind: 'model', fileName: 'app.ts', languageName: 'typescript',
			model: 'qwen3:8b', target: 'file', mode: 'summary', text: res.text, fromCache: res.fromCache,
		});
		assert.match(html, /Generated by local model: <code>qwen3:8b<\/code>/);
		assert.match(html, /The file registers two commands\./);
		assert.ok(!html.includes('let me look'), 'thinking must not reach the panel');
		assert.ok(!/Rule-based fallback/.test(html));
	});
});

test('e2e: selection explanation carries selection tags on the wire', async () => {
	await withServer((_req, res) => {
		res.writeHead(200, { 'Content-Type': 'application/json' });
		res.end(JSON.stringify({ response: 'The selection maps inputs.' }));
	}, async (baseUrl, captured) => {
		const sel = { startLine: 2, endLine: 4, text: 'const y = x.map(f);', before: 'import f from "./f";', after: undefined };
		const res = await makeService(baseUrl).explainSelection(doc(), sel, 'explain');
		assert.equal(res.status, 'ok');
		assert.equal(captured.length, 1);
		assert.match(captured[0].body.prompt ?? '', /<selection file="\/w\/app\.ts" language="typescript" lines="2-4">/);
		assert.ok((captured[0].body.prompt ?? '').includes('const y = x.map(f);'));
		if (res.status === 'ok' && res.source === 'model') {
			const html = renderBody({
				kind: 'model', fileName: 'app.ts', languageName: 'typescript',
				model: 'qwen3:8b', target: 'selection', mode: 'explain',
				text: res.text, fromCache: res.fromCache, lines: 'lines 2–4',
			});
			assert.match(html, /lines 2–4/);
			assert.match(html, /Generated by local model: <code>qwen3:8b<\/code>/);
			assert.match(html, /data-action="practice"/);
		}
	});
});

test('e2e: 404 yields modelMissing with a labelled fallback, never model-labelled', async () => {
	await withServer((_req, res) => {
		res.writeHead(404).end(JSON.stringify({ error: "model 'qwen3:8b' not found" }));
	}, async baseUrl => {
		const res = await makeService(baseUrl).explain(doc(), 'summary');
		assert.equal(res.status, 'error');
		if (res.status !== 'error') {
			return assert.fail('expected an error result');
		}
		assert.equal(res.kind, 'modelMissing');
		assert.ok(res.fallback, 'fallback should be attached');
		const html = renderBody({
			kind: 'error', fileName: 'app.ts', languageName: 'typescript', model: 'qwen3:8b',
			message: res.message, hint: res.hint, fallback: res.fallback,
		});
		assert.match(html, /Explanation failed/);
		assert.match(html, /Rule-based fallback/);
		assert.ok(!/Generated by local model/.test(html));
	});
});

test('e2e: slow response hits the configured timeout', async () => {
	await withServer((_req, res) => {
		setTimeout(() => {
			res.writeHead(200, { 'Content-Type': 'application/json' });
			res.end(JSON.stringify({ response: 'too late' }));
		}, 300);
	}, async baseUrl => {
		const res = await makeService(baseUrl, 50).explain(doc(), 'summary');
		assert.equal(res.status, 'error');
		if (res.status === 'error') {
			assert.equal(res.kind, 'timeout');
		}
	});
});

test('e2e: streamed NDJSON chunks accumulate and reach the panel', async () => {
	await withServer((_req, res) => {
		res.writeHead(200, { 'Content-Type': 'application/x-ndjson' });
		// Chunk boundaries deliberately mid-token — the client must reassemble.
		res.write('{"response":"The file ","done":false}\n{"response":"registers ');
		res.write('commands.","done":false}\n{"response":"","done":true}\n');
		res.end();
	}, async (baseUrl, captured) => {
		const tokens: string[] = [];
		const res = await makeService(baseUrl).explain(doc(), 'summary', false, { onToken: t => tokens.push(t) });
		assert.equal(captured[0].body.stream, true, 'onToken switches the request to streaming');
		if (res.status !== 'ok' || res.source !== 'model') {
			return assert.fail('expected a model result');
		}
		assert.equal(res.text, 'The file registers commands.');
		assert.deepEqual(tokens, ['The file ', 'The file registers commands.']);
	});
});

test('e2e: thinking chunks in a stream never reach the visible answer', async () => {
	await withServer((_req, res) => {
		res.writeHead(200, { 'Content-Type': 'application/x-ndjson' });
		res.write('{"thinking":"pondering quietly","done":false}\n');
		res.end('{"response":"Visible answer.","done":true}\n');
	}, async baseUrl => {
		const tokens: string[] = [];
		const res = await makeService(baseUrl).explain(doc(), 'summary', false, { onToken: t => tokens.push(t) });
		if (res.status !== 'ok' || res.source !== 'model') {
			return assert.fail('expected a model result');
		}
		assert.equal(res.text, 'Visible answer.');
		assert.ok(!tokens.some(t => t.includes('pondering')), 'thinking field must not leak into tokens');
	});
});

test('e2e: connection refused maps to unavailable with fallback', async () => {
	// Nothing listens here — provable failure, same shape as Ollama stopped.
	const res = await makeService('http://127.0.0.1:1').explain(doc(), 'summary');
	assert.equal(res.status, 'error');
	if (res.status === 'error') {
		assert.equal(res.kind, 'unavailable');
		assert.ok(res.fallback);
	}
});
