// Every data-action emitted by the webview must have a handler in the
// dispatcher — this is the contract that keeps the buttons wired.
test('every rendered data-action has a dispatchWebviewMessage handler', () => {
	const states: ViewState[] = [
		{ kind: 'model', fileName: 'a.ts', languageName: 'ts', model: 'm', target: 'file', mode: 'summary', text: 'x', fromCache: false },
		{ kind: 'model', fileName: 'a.ts', languageName: 'ts', model: 'm', target: 'file', mode: 'detail', text: 'x', fromCache: false },
		{ kind: 'model', fileName: 'a.ts', languageName: 'ts', model: 'm', target: 'selection', mode: 'explain', text: 'x', fromCache: false, lines: 'lines 3-9' },
		{ kind: 'model', fileName: 'a.ts', languageName: 'ts', model: 'm', target: 'selection', mode: 'learn', text: 'x', fromCache: false, lines: 'lines 3-9' },
		{ kind: 'quiz', fileName: 'a.ts', languageName: 'ts', model: 'm', question: 'q?', lines: 'lines 3-9' },
		{ kind: 'quizResult', fileName: 'a.ts', languageName: 'ts', model: 'm', question: 'q?', answer: 'a', text: 'fb', lines: 'lines 3-9' },
		{ kind: 'error', fileName: 'a.ts', languageName: 'ts', model: 'm', message: 'e', hint: 'h', lines: 'lines 3-9' },
	];
	for (const state of states) {
		const actions = [...renderBody(state).matchAll(/data-action="([^"]+)"/g)].map(m => m[1]);
		assert.ok(actions.length > 0, `state ${state.kind} should offer actions`);
		for (const action of actions) {
			assert.ok(
				WEBVIEW_MESSAGE_TYPES.includes(action as WebviewMessageType),
				`unhandled webview action "${action}" in ${state.kind} state`,
			);
		}
	}
});

test('selection views show the line range and learning actions', () => {
	const html = renderBody({
		kind: 'model', fileName: 'a.ts', languageName: 'TypeScript', model: 'm',
		target: 'selection', mode: 'explain', text: 'It maps keys.', fromCache: false,
		lines: 'lines 3–9',
	});
	assert.match(html, /lines 3–9/);
	assert.match(html, /data-action="learn"/);
	assert.match(html, /data-action="practice"/);
	assert.match(html, /data-action="retry"/);
	assert.match(html, /data-action="file"/);
});

test('learn mode renders parsed sections as expandable details', () => {
	const html = renderBody({
		kind: 'model', fileName: 'a.ts', languageName: 'TypeScript', model: 'm',
		target: 'selection', mode: 'learn', text: 'raw', fromCache: false,
		lines: 'lines 3–9',
		sections: [
			{ heading: 'Purpose', body: 'Sorts the list.' },
			{ heading: 'Remember this', body: '<b>unsafe</b>' },
		],
	});
	assert.match(html, /<details class="learn" open>\s*<summary>Purpose<\/summary>/);
	assert.match(html, /<summary>Remember this<\/summary>/);
	assert.ok(!html.includes('<b>unsafe</b>'), 'section bodies are escaped');
});

test('quiz state renders question, answer input and bounded actions', () => {
	const html = renderBody({
		kind: 'quiz', fileName: 'a.ts', languageName: 'TypeScript', model: 'm',
		question: 'What does x() return?', lines: 'lines 3–9',
	});
	assert.match(html, /What does x\(\) return\?/);
	assert.match(html, /<textarea id="tancode-answer"/);
	assert.match(html, /data-action="submit-answer"/);
	assert.match(html, /data-action="new-question"/);
	assert.ok(!html.includes('Reference answer'), 'no answer leak before submit');
});

test('quiz result shows question, own answer and assessment', () => {
	const html = renderBody({
		kind: 'quizResult', fileName: 'a.ts', languageName: 'TypeScript', model: 'm',
		question: 'Why the check?', answer: 'It guards null.', text: 'Mostly right: it guards undefined.',
		lines: 'lines 3–9',
	});
	assert.match(html, /Why the check\?/);
	assert.match(html, /It guards null\./);
	assert.match(html, /Mostly right/);
	assert.match(html, /data-action="new-question"/);
});

test('partial model state streams escaped text with no action buttons', () => {
	const html = renderBody({
		kind: 'model', fileName: 'a.ts', languageName: 'TypeScript', model: 'm',
		target: 'file', mode: 'summary', text: 'Partial <script>bad</script> text',
		fromCache: false, partial: true,
	});
	assert.match(html, /Generating/);
	assert.ok(!html.includes('data-action'), 'controls hidden while streaming');
	assert.ok(!html.includes('<script>bad'), 'partial model output is escaped');
	assert.match(html, /Partial &lt;script&gt;bad&lt;\/script&gt; text/);
});

test('conversation view renders toolbar, context card, feed and composer', () => {
	const html = renderConversation({
		watching: 'app.ts',
		model: 'qwen3:8b',
		paused: false,
		generating: false,
		proactiveCount: 2,
		proactiveMax: 12,
		context: { kind: 'empty', fileName: 'app.ts' },
		entries: [
			userMessage(1, 'what does this do?'),
			assistantMessage(2, 'insight', 'This loop is O(n^2).', { dismissible: true }),
			assistantMessage(3, 'answer', 'It maps over the list.'),
		],
	});
	assert.match(html, /Watching app\.ts/);
	assert.match(html, /data-action="pause"/);
	assert.match(html, /what does this do\?/);
	assert.match(html, /tag insight/);
	assert.match(html, /data-action="dismiss" data-id="2"/);
	assert.match(html, /id="tancode-chat"/);
	assert.match(html, /data-action="send-chat"/);
	assert.ok(!html.includes('data-action="stop"'), 'stop hidden when idle');
});

test('paused + generating chrome renders pause-resume and stop', () => {
	const html = renderConversation({
		model: 'm', paused: true, generating: true, proactiveCount: 0, proactiveMax: 12,
		entries: [assistantMessage(1, 'info', 'Generation stopped.')],
	});
	assert.match(html, /data-action="resume"/);
	assert.match(html, /data-action="stop"/);
	assert.match(html, /proactive paused/);
});

test('dismissed and partial entries render correctly', () => {
	const html = renderConversation({
		model: 'm', paused: false, generating: false, proactiveCount: 0, proactiveMax: 12,
		entries: [
			assistantMessage(1, 'insight', 'hidden', { dismissed: true }),
			assistantMessage(2, 'answer', 'still typing', { partial: true }),
		],
	});
	assert.ok(!html.includes('hidden'), 'dismissed entry is skipped');
	assert.match(html, /still typing/);
});

test('feed entries escape user and model text', () => {
	const html = renderConversation({
		model: 'm', paused: false, generating: false, proactiveCount: 0, proactiveMax: 12,
		entries: [
			userMessage(1, '<img src=x onerror=alert(1)>'),
			assistantMessage(2, 'insight', '<script>bad</script>'),
		],
	});
	assert.ok(!html.includes('<img src=x'), 'user text escaped');
	assert.ok(!html.includes('<script>bad'), 'assistant text escaped');
});
